/**
 * Source credibility, platform routing, and misinformation filtering.
 *
 * Two ideas drive this module:
 *
 * 1. A source's trust is a *derived* fact, not a label. The caller supplies
 *    observable evidence (is it the vendor's own domain? does the Bilibili
 *    account carry a blue lightning? did the account's title and bio actually
 *    mention toys/models?) and the module returns a tier with reasons.
 * 2. Anything unverifiable is surfaced, not averaged away. Accounts without a
 *    lightning bolt become a user-confirmation prompt, and single-source,
 *    AI-generated, or low-tier claims are marked display-only so they can never
 *    be filed into the knowledge base.
 * @module @dsh-plugin/tokusatsu-gunpla/sources
 */

